import express from "express";
import cors from "cors";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import rateLimit from "express-rate-limit";
import { notFoundHandler, errorMiddleware } from "./middlewares/error.middleware";
import authRoutes from "./routes/admin.auth.routes";
import productRoutes from "./routes/product.routes";
import categoryRoutes from "./routes/category.routes";
import orderRoutes from "./routes/order.routes";
import adminRoutes from "./routes/admin.routes";
import settingsRoutes from "./routes/settings.routes";
import contactRoutes from "./routes/contact.routes";
import uploadRoutes from "./routes/upload.routes";
const app = express();
app.use(helmet());
app.use(cors({ origin: true, credentials: true }));
app.use(express.json({ limit: "10mb" }));
app.use(cookieParser());
app.use("/api", rateLimit({ windowMs: 15 * 60 * 1000, max: 300, standardHeaders: true, legacyHeaders: false }));
app.get("/", (_req, res) => res.json({ ok: true, service: "oofy-backend" }));
app.get("/api/health", (_req, res) => res.json({ ok: true, service: "oofy-backend" }));
app.use("/api/admin/auth", authRoutes);
app.use("/api/products", productRoutes);
app.use("/api/categories", categoryRoutes);
app.use("/api/orders", orderRoutes);
app.use("/api/admin", adminRoutes);
app.use("/api/admin/settings", settingsRoutes);
app.use("/api/admin/uploads", uploadRoutes);
app.use("/api/contact", contactRoutes);
app.use(notFoundHandler);
app.use(errorMiddleware);
export default app;
